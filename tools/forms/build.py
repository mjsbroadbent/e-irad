#!/usr/bin/env python3
"""Builds the printed forms (PDF) and the forms list.

    python3 tools/forms/build.py              # all forms of this site
    python3 tools/forms/build.py PRS-3        # one form

Writes forms/<CODE>.pdf and assets/forms.js (the list the Permits and forms page and the service pages read).
Form contents are in specs_*.py; the catalogue (codes, titles, issuing bodies, services) is catalog.py.
Post forms (P-*) are written to ../irad-post/forms/ (a clone of the post site next to this repo).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import catalog  # noqa: E402
import engine  # noqa: E402

ROOT = HERE.parent.parent
OUT = ROOT / "forms"
POST_OUT = ROOT.parent / "irad-post" / "forms"      # post forms are published on post.iradgov.org
CYR = re.compile("[Ѐ-ӿ]")


def load_specs():
    specs = {}
    for p in sorted(HERE.glob("specs_*.py")):
        mod = __import__(p.stem)
        specs.update(mod.FORMS)
    return specs


LOOK = dict(zip("аеорсукңшчдплөүитнмвгзбжыйАЕОРСУК", ["a", "e", "o", "r", "s", "u", "k", "ñ", "sh", "ch", "d", "p", "l", "ö", "ü", "i", "t", "n", "m", "v", "g", "z", "b", "j", "ı", "y", "A", "E", "O", "R", "S", "U", "K"]))


def fix_ir(obj):
    """Iradi is written in Latin letters: replace stray Cyrillic look-alikes and ğ in every "ir" string."""
    if isinstance(obj, dict):
        if isinstance(obj.get("ir"), str):
            obj["ir"] = "".join(LOOK.get(ch, ch) for ch in obj["ir"]).replace("ğ", "g")
        for v in obj.values():
            fix_ir(v)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            fix_ir(v)


def check_ir(obj, path="", bad=None):
    bad = [] if bad is None else bad
    if isinstance(obj, dict):
        if "ir" in obj and isinstance(obj["ir"], str) and (CYR.search(obj["ir"]) or "ğ" in obj["ir"]):
            bad.append((path, obj["ir"]))
        for k, v in obj.items():
            check_ir(v, f"{path}.{k}", bad)
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            check_ir(v, f"{path}[{i}]", bad)
    return bad


def main():
    only = sys.argv[1:]
    specs = load_specs()
    cat = {c[0]: c for c in catalog.FORMS}
    OUT.mkdir(exist_ok=True)
    for o in (specs, catalog.FORMS, catalog.AG, engine.COMMON):
        fix_ir(o)
    bad = check_ir(specs) + check_ir(catalog.FORMS) + check_ir(engine.COMMON)
    if bad:
        for p, s in bad:
            print("Cyrillic or ğ in Iradi:", p, s[:80])
        sys.exit(1)
    n = 0
    for code, spec in specs.items():
        if only and code not in only:
            continue
        c = cat[code]
        spec = dict(spec, code=code, agency=catalog.AG[c[1]], title=c[4])
        dest = POST_OUT if c[1] == "post" else OUT
        dest.mkdir(exist_ok=True)
        pages = engine.render(dest / f"{code}.pdf", spec)
        print(f"{code}: {pages} page(s)")
        n += 1
    # the list for the site
    out = {"agencies": catalog.AG, "list": []}
    for code, ag, ct, svc, title in catalog.FORMS:
        url = (f"https://post.iradgov.org/forms/{code}.pdf" if ag == "post" else f"/forms/{code}.pdf")
        f = (POST_OUT if ag == "post" else OUT) / f"{code}.pdf"
        item = {"code": code, "agency": ag, "cat": ct, "service": svc, "title": title, "url": url}
        if f.exists():
            item["kb"] = round(f.stat().st_size / 1024)
        out["list"].append(item)
    (ROOT / "assets" / "forms.js").write_text(
        "/* Printed forms (generated by tools/forms/build.py from tools/forms/catalog.py: edit there). */\n"
        "window.E_FORMS = " + json.dumps(out, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print(n, "forms")


if __name__ == "__main__":
    main()
